// Seeded randomness. Every procedural shape in the world is built from a fixed seed so the scene
// looks identical on every visit and between the lab and the live site.

/** mulberry32: a tiny, well distributed 32-bit PRNG returning floats in [0, 1). */
export function createRandom(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
